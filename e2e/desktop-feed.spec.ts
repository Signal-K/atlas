import { test, expect } from '@playwright/test'
import { seedSignedInUser } from './support/auth'

test('desktop feed saves events into the adjacent calendar and persists after reload', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await seedSignedInUser(page)
  await page.addInitScript(() => localStorage.setItem('atlas-theme', 'dark'))
  await page.route('**/api/**', route => route.abort())
  await page.goto('/app/hub')
  await expect(page.getByRole('heading', { name: 'Your sky, worth stepping out for.' })).toBeVisible()
  await page.evaluate(async () => {
    const { db } = await import('/src/lib/db.ts')
    await db.skyEvents.put({ id: 'desktop-meteor', kind: 'meteor_shower', target: 'perseids', title: 'An evening of shooting stars', description: 'Find a dark spot, settle in, and give your eyes time to adjust.', startsAt: new Date().toISOString(), endsAt: new Date(Date.now() + 86400000).toISOString(), updatedAt: new Date().toISOString() })
  })
  await page.reload()
  const card = page.locator('.desktop-event-card').filter({ hasText: 'An evening of shooting stars' })
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: '+ Add to calendar' }).click()
  await expect(card.getByRole('button', { name: '✓ In your calendar' })).toHaveAttribute('aria-pressed', 'true')
  const agenda = page.getByRole('complementary', { name: 'Your calendar' })
  await expect(agenda.locator('.desktop-upcoming')).toContainText('An evening of shooting stars')
  await page.reload()
  await expect(card.getByRole('button', { name: '✓ In your calendar' })).toBeVisible()
  await card.getByRole('button', { name: '✓ In your calendar' }).click()
  await expect(card.getByRole('button', { name: '+ Add to calendar' })).toHaveAttribute('aria-pressed', 'false')
  await expect(agenda.locator('.desktop-upcoming')).toHaveCount(0)
  await page.getByRole('button', { name: 'Community', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Field Feed' })).toBeVisible()
  await page.getByRole('button', { name: 'Tonight', exact: true }).click()
  await expect(page.locator('.desktop-event-feed')).toHaveCount(0)
  await expect(page.locator('.dt-feed')).toHaveCount(0)
  await page.getByRole('button', { name: 'Sky events', exact: true }).click()
  await expect(card).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('desktop layout adapts to a narrower window and returns to the mobile hub', async ({ page }) => {
  await seedSignedInUser(page)
  await page.route('**/api/**', route => route.abort())
  await page.setViewportSize({ width: 1024, height: 900 })
  await page.goto('/app/hub')
  await expect(page.locator('.desktop-workspace')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.desktop-workspace')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
